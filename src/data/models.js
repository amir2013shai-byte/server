// Построители 3D-моделей карт: красивые детальные примитивы с подсветкой.
// Формат части: { shape, pos:[x,y,z], rot:[x,y,z], scale:[x,y,z], color, emissive, opacity }
// Основание модели — y=0 (ноги/низ), модель «смотрит» вдоль +Z.

export const SHAPES = ['box', 'sphere', 'cylinder', 'cone', 'torus', 'capsule', 'ring', 'halfsphere', 'wedge'];

export function P(shape, pos, scale, color, opts = {}) {
  return {
    shape,
    pos: pos.slice(),
    rot: (opts.rot || [0, 0, 0]).slice(),
    scale: scale.slice(),
    color,
    emissive: opts.emissive || '#000000',
    opacity: opts.opacity !== undefined ? opts.opacity : 1
  };
}

